"""Build CNA data files from content/cna/cna_src.py (four languages authored together).
Writes data/cna-a.js and data/ma-cna.js, and merges French/Spanish strings into data/i18n-fr.js and data/i18n-es.js.
Usage: python3 content/cna/build_cna.py   (run from the repo root; safe to re-run)"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cna_src import CH
from ma_tags import HHA_TAGS, CNA_TAGS

# MA D&S written exam outline (MA Candidate Handbook 5.2026): area id, questions on the 60-question exam, names (en, ht, fr, es)
AREAS = [
 ("role", 9, ("Role and Responsibility","Wòl ak responsablite","Rôle et responsabilités","Función y responsabilidades")),
 ("basic", 8, ("Basic Nursing Skills","Konpetans debaz swen enfimyè","Soins infirmiers de base","Destrezas básicas de enfermería")),
 ("disease", 7, ("Disease Process","Maladi yo","Processus des maladies","Proceso de las enfermedades")),
 ("rights", 6, ("Resident Rights","Dwa rezidan yo","Droits des résidents","Derechos de los residentes")),
 ("safety", 6, ("Safety","Sekirite","Sécurité","Seguridad")),
 ("comm", 5, ("Communication","Kominikasyon","Communication","Comunicación")),
 ("infect", 4, ("Infection Control","Kontwòl enfeksyon","Contrôle des infections","Control de infecciones")),
 ("mental", 4, ("Mental Health","Sante mantal","Santé mentale","Salud mental")),
 ("personal", 4, ("Personal Care","Swen pèsonèl","Soins personnels","Cuidado personal")),
 ("impaired", 3, ("Care Impaired","Rezidan ki gen pwoblèm memwa oswa sans","Soins aux personnes avec troubles cognitifs ou sensoriels","Cuidado de personas con deterioro cognitivo o sensorial")),
 ("aging", 2, ("Aging Process and Restorative Care","Vyeyisman ak swen reyadaptasyon","Vieillissement et soins de réadaptation","Envejecimiento y cuidado restaurativo")),
 ("data", 2, ("Data Collection","Kolekte done","Collecte de données","Recopilación de datos")),
]
assert sum(a[1] for a in AREAS) == 60
AREA_IDS = {a[0] for a in AREAS}

fr, es = {}, {}
def tr(t):  # t = (en, ht, fr, es)
    en, ht, f, s = t
    for d, v in ((fr, f), (es, s)):
        if en in d and d[en] != v: print('WARN two translations for:', en[:70])
        d[en] = v
    return [ht, en]

chapters, sec_map, area_map = [], {}, {}
for c in CH:
    out = {"ch": c["ch"], "bp": tr(c["bp"]), "title": tr(c["title"]), "src": c["src"], "sections": [], "terms": [], "qs": []}
    for s in c["sections"]:
        out["sections"].append({"h": tr(s["h"]), "src": s["src"], "b": [[k] + tr(t) for k, t in s["b"]]})
    for t in c["terms"]:
        out["terms"].append([t[0], t[1]]); tr((t[0], t[1], t[2], t[3]))
    for q in c["qs"]:
        qid, ci, area, sec, term, *rest = q
        assert area in AREA_IDS, (qid, area)
        assert 0 <= sec < len(c["sections"]), (qid, sec)
        assert len(rest) == 6, qid
        ht = [r[1] for r in rest]; en = [r[0] for r in rest]
        for r in rest: tr(r)
        tr(term)
        out["qs"].append([qid, ci, [term[0], term[1]], ht, en])
        sec_map[qid] = sec; area_map[qid] = area
    chapters.append(out)

for k, v in list(HHA_TAGS.items()) + list(CNA_TAGS.items()):
    if v is not None:
        assert v in AREA_IDS, (k, v); area_map[k] = v
areas = []
for aid, n, names in AREAS:
    areas.append({"id": aid, "n": n, "ht": names[1], "en": names[0]}); tr(names)

hdr = "/* Generated by content/cna/build_cna.py from content/cna/cna_src.py. Edit the source, then re-run the build. */\n"
with open(os.path.join(ROOT, "data", "cna-a.js"), "w", encoding="utf-8") as f:
    f.write(hdr + "/* CNA guide chapters 2-7. Same format as the HHA data files (see data/hha-a.js). Sources: content/SOURCES.md */\n")
    f.write("(window.CNA = window.CNA || []).push(\n" + ",\n".join(json.dumps(c, ensure_ascii=False) for c in chapters) + ");\n")
    f.write("window.CNA_SEC = " + json.dumps(sec_map) + ";\n")
with open(os.path.join(ROOT, "data", "ma-cna.js"), "w", encoding="utf-8") as f:
    f.write(hdr + "/* Massachusetts CNA written exam outline (D&S / Headmaster candidate handbook 5.2026): 60 questions, 60 minutes, 76% to pass.\n"
            "   areas: content area and number of exam questions. map: question id -> area (HHA ids are reused in the CNA bank as 'c-<id>'; HHA-only questions are left out). */\n")
    f.write("window.MA_CNA = " + json.dumps({"exam": {"n": 60, "min": 60}, "areas": areas, "map": area_map}, ensure_ascii=False) + ";\n")

# merge translations into the i18n files
for lang, d in (("fr", fr), ("es", es)):
    p = os.path.join(ROOT, "data", "i18n-" + lang + ".js")
    src = open(p, encoding="utf-8").read()
    head, body = src.split("(window.I18N=window.I18N||{})." + lang + "=", 1)
    cur = json.loads(body.strip().rstrip(";"))
    for k, v in d.items():
        if k in cur and cur[k] != v: print(f'note {lang}: replacing existing translation for "{k[:60]}"')
        cur[k] = v
    with open(p, "w", encoding="utf-8") as f:
        f.write(head + "(window.I18N=window.I18N||{})." + lang + "=" + json.dumps(cur, ensure_ascii=False, indent=0) + ";\n")

cnt = {}
for a in area_map.values(): cnt[a] = cnt.get(a, 0) + 1
print("chapters", len(chapters), "new questions", len(sec_map), "strings", len(fr))
print("pool per area (exam):", ", ".join(f"{a}={cnt.get(a,0)}({n})" for a, n, _ in AREAS))

# The app loads data/web/*.js, made from the data files: refresh them.
import subprocess
subprocess.run(["node", os.path.join(ROOT, "tools", "split_web.js"), ROOT], check=True)
