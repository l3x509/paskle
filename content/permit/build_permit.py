"""Build the Massachusetts learner's permit data from content/permit/permit_src.py (four languages authored together).
Writes data/permit-a.js and merges French/Spanish strings into data/i18n-fr.js and data/i18n-es.js.
Fact source: Massachusetts Driver's Manual, Class D (RMV, April 2026) = source S7; every section and FAQ answer carries its manual pages.
Usage: python3 content/permit/build_permit.py   (run from the repo root; safe to re-run)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from permit_src import CH
from permit_faq import GROUPS, FAQ

SIGNS = {"stop", "yield", "rr", "school", "curve", "nouturn", "work", "smv"}
fr, es = {}, {}
def tr(t):  # t = (en, ht, fr, es) -> [ht, en]
    en, ht, f, s = t
    for d, v in ((fr, f), (es, s)):
        if en in d and d[en] != v: print('WARN two translations for:', en[:70])
        d[en] = v
    return [ht, en]

chapters, sec_map, ids = [], {}, set()
for c in sorted(CH, key=lambda c: c["ch"]):
    out = {"ch": c["ch"], "bp": tr(c["bp"]), "title": tr(c["title"]), "src": ["S7"], "sections": [], "terms": [], "qs": []}
    for s in c["sections"]:
        sec = {"h": tr(s["h"]), "src": ["S7"], "pg": s["pg"], "b": [[k] + tr(t) for k, t in s["b"]]}
        if s.get("sign"):
            assert s["sign"] in SIGNS, s["sign"]; sec["sign"] = s["sign"]
        out["sections"].append(sec)
    for t in c["terms"]:
        out["terms"].append([t[0], t[1]]); tr(t)
    for q in c["qs"]:
        qid, ci, sec, term, *rest = q
        sign = rest.pop() if len(rest) == 7 else None
        assert len(rest) == 6 and 0 <= ci <= 3, qid
        assert 0 <= sec < len(c["sections"]), (qid, sec)
        assert qid not in ids, qid; ids.add(qid)
        assert sign is None or sign in SIGNS, (qid, sign)
        for r in rest: tr(r)
        tr(term)
        row = [qid, ci, [term[0], term[1]], [r[1] for r in rest], [r[0] for r in rest]]
        if sign: row.append(sign)
        out["qs"].append(row)
        sec_map[qid] = sec
    chapters.append(out)

gkeys = [g[0] for g in GROUPS]
groups = {k: tr(t) for k, t in GROUPS}
faq, seenq = [], set()
for grp, qq, aa, pg, src in sorted(FAQ, key=lambda f: gkeys.index(f[0])):
    assert grp in groups and qq[0] not in seenq, qq[0]; seenq.add(qq[0])
    a = tr(qq); b = tr(aa)
    faq.append([a[0], a[1], b[0], b[1], src, pg, grp])

hdr = "/* Generated by content/permit/build_permit.py from content/permit/permit_src.py. Edit the source, then re-run the build. */\n"
with open(os.path.join(ROOT, "data", "permit-a.js"), "w", encoding="utf-8") as f:
    f.write(hdr + "/* Massachusetts learner's permit guide (8 chapters), questions and FAQ. Facts: Massachusetts Driver's Manual, Class D, April 2026 (S7); pg = manual page numbers. */\n")
    f.write("window.PERMIT = [\n" + ",\n".join(json.dumps(c, ensure_ascii=False) for c in chapters) + "];\n")
    f.write("window.PERMIT_SEC = " + json.dumps(sec_map) + ";\n")
    f.write("window.PERMIT_FAQ = [\n" + ",\n".join(json.dumps(x, ensure_ascii=False) for x in faq) + "];\n")
    f.write("window.PERMIT_FAQ_GROUPS = " + json.dumps(groups, ensure_ascii=False) + ";\n")

for lang, d in (("fr", fr), ("es", es)):
    p = os.path.join(ROOT, "data", "i18n-" + lang + ".js")
    src = open(p, encoding="utf-8").read()
    head, body = src.split("(window.I18N=window.I18N||{})." + lang + "=", 1)
    cur = json.loads(body.strip().rstrip(";"))
    for k, v in d.items():
        if k in cur and cur[k] != v: print(f'note {lang}: replacing existing translation for "{k[:60]}"')
        cur[k] = v
    with open(p, "w", encoding="utf-8") as f:
        f.write(head + "(window.I18N=window.I18N||{})." + lang + "=" + json.dumps(cur, ensure_ascii=False, indent=0) + ";\n")

print("chapters", len(chapters), "questions", len(sec_map), "faq", len(faq), "strings", len(fr))
print("per chapter:", ", ".join(f"c{c['ch']}={len(c['qs'])}" for c in chapters))

# The app loads data/web/*.js, made from the data files: refresh them.
import subprocess
subprocess.run(["node", os.path.join(ROOT, "tools", "split_web.js"), ROOT], check=True)
